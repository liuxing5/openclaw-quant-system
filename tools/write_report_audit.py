"""把 43 笔审计表 + 月度表写入报告，替换原来的 6.6 节选。"""
import pandas as pd

REPORT = "docs/策略诊断与隔夜八步法v2_2026-11-21.md"
d = pd.read_csv("docs/overnight_v2/v3_audit.csv")
m = pd.read_csv("docs/overnight_v2/v3_monthly.csv")

rows = []
for r in d.itertuples():
    rows.append(
        f"| {r.date} | {r.code} | {r.name} | {r.buy:.2f} | {r.sell_time} | {r.sell:.2f} | "
        f"{r.reason} | {r.net*100:+.2f}% | {r.t1_close_ret*100:+.2f}% | "
        f"{r.t2_ret*100:+.2f}% | {r.t3_ret*100:+.2f}% |")
table = "\n".join(rows)

mrows = []
for r in m.itertuples():
    mrows.append(f"| {r.ym} | {r.trades} | {r.wins}/{r.losses} | {r.monthly*100:+.2f}% |")
mtable = "\n".join(mrows)

new = f"""### 6.6 逐笔明细（全部 43 笔，前复权）

> 价格口径：前复权（与同花顺/东财「前复权」一致），所以绝对价可能和你看到的不复权 K 线不同，**百分比收益不受影响**。
> 买入 = T 日 14:50 的 5 分钟收盘；卖出 = T+1 的 09:30 开盘（高开/深水）或 10:00 收盘（或 −2% 止损）。
> 净收益已扣 0.25% 往返成本。T+1 收盘 / T+2 / T+3 是「如果继续持有」的走势，用来说明为什么必须次日早盘卖。

| 信号日 | 代码 | 名称 | 买入价 | 卖出时间 | 卖出价 | 原因 | 净收益 | T+1收盘 | T+2 | T+3 |
|---|---|---:|---:|---|---:|---|---:|---:|---:|---:|
{table}

### 6.7 月度收益（逐月，13 个有交易的月份）

| 月份 | 笔数 | 胜/负 | 月收益 |
|---|---:|---:|---:|
{mtable}

**没有交易的月份（2025-01、2025-07、2026-04）收益为 0，未列出。**
13 个月中 **10 个为正、3 个为负**（2025-04 −0.23%、2025-06 −2.25%、2026-01 −0.31%），
不是「每月都为正」；最大单月亏损 −2.25%。

### 6.8 审计结论（为什么「后面几天跌」还能赚）

1. **策略不持有后面几天**：T 日 14:50 买入，T+1 09:30 或 10:00 卖出，只承担 1 夜 + 早盘 30 分钟。
   表里 T+2 均值 −0.11%、T+3 均值 +0.53%，说明早盘之后 edge 基本消失——这正是「次日 10:00 前必须卖」的原因。
2. **收益来自次日早盘的冲高/高开**：16 笔高开 ≥+0.5% 的票在 09:30 直接落袋（全部盈利）；
   其余 25 笔在 10:00 前卖出，72% 盈利；只有 2 笔触发 −2% 止损。
3. **价格完整性**：43 笔的买入价全部落在 T 日 5 分钟高低区间内，卖出价全部落在 T+1 5 分钟区间内；
   T/T+1 的复权因子一致（没有除权导致的错位）。审计文件：`docs/overnight_v2/v3_audit.csv`。
4. **典型对照**：海光信息 2025-02-28 买入 157.92，T+1 开盘 159.73（+1.15%）卖出，随后 T+1 收盘 150.63（−4.6%）——
   如果不卖、看后面几天，确实是大跌；策略赚的是开盘那一下，不是后面的走势。
"""

s = open(REPORT, encoding="utf-8").read()
start = s.index("### 6.6 逐笔（节选）")
end = s.index("---\n\n## 七、执行与落地")
s = s[:start] + new + "\n" + s[end:]
open(REPORT, "w", encoding="utf-8").write(s)
print("updated", REPORT, len(table), "chars")
